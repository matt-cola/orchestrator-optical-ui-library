// Copies Leaflet's stylesheet into a TypeScript module.
//
// Next.js refuses global CSS imported from a package, so the map component
// injects the stylesheet itself (see OpticalMapStyles) instead of asking every
// consumer to import `leaflet/dist/leaflet.css` in their own app.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const css = readFileSync(require.resolve('leaflet/dist/leaflet.css'), 'utf8');
const { version } = require('leaflet/package.json');

writeFileSync(
  new URL('../src/components/leafletCss.generated.ts', import.meta.url),
  `// Generated by scripts/generate-leaflet-css.mjs from leaflet@${version}. Do not edit.\n` +
    `export const LEAFLET_CSS = ${JSON.stringify(css)};\n`,
);
